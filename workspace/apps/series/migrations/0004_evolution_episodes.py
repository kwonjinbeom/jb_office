    for number, screen, title, period, hook, steps, sources in EPISODES:
        values = {"screen": screen, "title": title, "period": period, "hook": hook,
                  "points": "\n".join(steps), "sources": "\n".join(sources)}
        ep = Episode.objects.filter(number=number).first()
        if ep is None:
            Episode.objects.create(number=number, **values)
