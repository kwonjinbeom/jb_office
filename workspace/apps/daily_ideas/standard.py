def to_markdown(values: dict[str, str], title: str = "아이디어 검색 표준") -> str:
    """항목별 값을 하나의 Markdown 문서로. 빈 항목은 뺀다."""
    lines = [f"# {title}", ""]
    number = 0
    for name, label, _, _ in SECTIONS:
        text = (values.get(name) or "").strip()
        if not text:
            continue
        number += 1
        lines += [f"## {number}. {label}", "", text, ""]
    return "\n".join(lines).rstrip() + "\n"


